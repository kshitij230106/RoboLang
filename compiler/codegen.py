from dataclasses import dataclass
from typing import List

from compiler.ir import IRProgram

# ==========================================
# Bytecode Opcodes
# ==========================================

OP_MOVE = 1
OP_TURN = 2


# Direction codes
DIR_LEFT = 1
DIR_RIGHT = 2


# ==========================================
# Bytecode Program
# ==========================================


@dataclass
class BytecodeProgram:

    instructions: List[int]

    def __str__(self):

        if not self.instructions:
            return "(empty bytecode)"

        return " ".join(str(value) for value in self.instructions)


# ==========================================
# Code Generator
# ==========================================


class CodeGenerator:

    def generate(self, ir_program):

        if not isinstance(ir_program, IRProgram):
            raise TypeError("Code Generator expected an IRProgram.")

        bytecode = []

        for instruction in ir_program.instructions:

            # ------------------------------
            # MOVE
            # ------------------------------

            if instruction.opcode == "MOVE":

                bytecode.append(OP_MOVE)
                bytecode.append(instruction.operand)

            # ------------------------------
            # TURN
            # ------------------------------

            elif instruction.opcode == "TURN":

                bytecode.append(OP_TURN)

                if instruction.operand == "LEFT":
                    bytecode.append(DIR_LEFT)

                elif instruction.operand == "RIGHT":
                    bytecode.append(DIR_RIGHT)

                else:
                    raise ValueError(f"Invalid direction: " f"{instruction.operand}")

            else:

                raise ValueError(f"Unknown IR opcode: " f"{instruction.opcode}")

        return BytecodeProgram(bytecode)


