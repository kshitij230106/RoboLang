if __name__ == "__main__":

    from compiler.lexer import Lexer
    from compiler.parser import Parser
    from compiler.semantic import SemanticAnalyzer
    from compiler.ir import IRGenerator

    source = """
    START

    MOVE 100
    TURN RIGHT
    MOVE 50
    TURN LEFT
    MOVE 30

    STOP
    """

    try:

        # 1. Lexer
        lexer = Lexer(source)
        tokens = lexer.tokenize()

        print("✓ Lexical Analysis Successful")

        # 2. Parser
        parser = Parser(tokens)
        program = parser.parse()

        print("✓ Syntax Analysis Successful")

        # 3. Semantic Analysis
        analyzer = SemanticAnalyzer()
        analyzer.analyze(program)

        print("✓ Semantic Analysis Successful")

        # 4. IR Generation
        ir_generator = IRGenerator()
        ir_program = ir_generator.generate(program)

        print("✓ IR Generation Successful")

        print("\nIR:")
        print("--------------------------------")
        print(ir_program)

        # 5. Code Generation
        code_generator = CodeGenerator()
        bytecode = code_generator.generate(ir_program)

        print("\n✓ Code Generation Successful")

        print("\nGenerated Bytecode:")
        print("--------------------------------")
        print(bytecode)

    except Exception as error:

        print(f"\n❌ Error: {error}")
